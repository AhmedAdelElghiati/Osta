  private getLocalReply(input: string): string {
    const text = input.toLowerCase().trim();

    for (const item of this.knowledge) {
      for (const key of item.keywords) {
        if (text.includes(key.toLowerCase())) {
          return item.reply;
        }
      }
    }

    return (
      'معلش مفهمتش سؤالك 🤔\n' +
      'جرب تسألني عن:\n' +
      '• إزاي أحجز فني\n' +
      '• التسجيل كحرفي أو عميل\n' +
      '• طرق الدفع والأسعار\n' +
      '• أي خدمة (سباك، كهربائي، نجار...)'
    );
  }

  // ============================================================
  // Helpers
  // ============================================================
  ngAfterViewChecked(): void {
    if (this.shouldScroll) {
      this.scrollToBottom();
      this.shouldScroll = false;
    }
  }

  private scrollToBottom(): void {
    const el = this.scrollContainer?.nativeElement;
    if (el) {
      el.scrollTop = el.scrollHeight;
    }
  }

  toggleChat(): void {
    this.isOpen = !this.isOpen;
    if (this.isOpen) {
      this.shouldScroll = true;
    }
  }

  sendQuickReply(text: string): void {
    this.userInput = text;
    this.sendMessage();
  }

  private pushBot(text: string, isError = false): void {
    this.ngZone.run(() => {
      this.messages.push({ sender: 'bot', text, isError });
      this.loading = false;
      this.shouldScroll = true;
      this.cdr.detectChanges();
    });
  }

  sendMessage(): void {
    const message = this.userInput.trim();
    if (!message || this.loading) {
      return;
    }

    this.ngZone.run(() => {
      this.messages.push({ sender: 'user', text: message });
      this.userInput = '';
      this.loading = true;
      this.shouldScroll = true;
      this.cdr.detectChanges();
    });

    setTimeout(() => {
      const reply = this.getLocalReply(message);
      this.pushBot(reply);
    }, 400);
  }

  constructor(
    private ngZone: NgZone,
    private cdr: ChangeDetectorRef
  ) {}
